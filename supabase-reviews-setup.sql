-- Indian Chicken Shop: customer reviews table
-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text check (char_length(name) <= 60),
  product text not null check (char_length(product) between 1 and 100),
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(message) between 1 and 1200),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

-- Grant only the operations used by the website; RLS policies still apply.
grant select, insert on table public.reviews to anon, authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;

-- Public visitors can read approved reviews only.
drop policy if exists "Anyone can read approved reviews" on public.reviews;
create policy "Anyone can read approved reviews"
  on public.reviews for select to anon, authenticated
  using (approved = true);

-- Public visitors can submit reviews only in the pending state.
drop policy if exists "Visitors can submit pending reviews" on public.reviews;
create policy "Visitors can submit pending reviews"
  on public.reviews for insert to anon, authenticated
  with check (approved = false);

-- Do not create public update or delete policies.
-- To approve a review: Supabase Dashboard > Table Editor > reviews > set approved=true.
